const PAGE_TITLES = {
  home: "meta.title.home",
  gallery: "meta.title.gallery",
  about: "meta.title.about",
  contact: "meta.title.contact"
};

function getLang() {
  const saved = localStorage.getItem("gs-lang");
  if (saved === "it" || saved === "en") return saved;
  return "it";
}

function setLang(lang) {
  if (lang !== "it" && lang !== "en") return;
  localStorage.setItem("gs-lang", lang);
  applyLang(lang);
}

function t(key, lang = getLang()) {
  return (I18N[lang] && I18N[lang][key]) || I18N.it[key] || key;
}

function applyLang(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key, lang);
    el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key, lang);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    el.setAttribute("aria-label", t(key, lang));
  });

  const page = document.body.dataset.page;
  if (page && PAGE_TITLES[page]) {
    document.title = t(PAGE_TITLES[page], lang);
  }

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  if (typeof refreshLightboxLang === "function") {
    refreshLightboxLang();
  }

  window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

function initI18n() {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });
  applyLang(getLang());
}
